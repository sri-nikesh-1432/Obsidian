"""Personal RAG: ingestion, per-user isolated vector storage, retrieval, answers.

Isolation model (required by the spec — never a global index with filters):

    RAG#<user_id>  (partition key)
        ├── INSTANCE            (consent + status)
        ├── PROFILE             (profile summary chunk)
        ├── DOC#<document_id>   (index record)
        └── CHUNK#<doc_id>#<n>  (text + embedding vector)

Retrieval ALWAYS queries a single partition derived from the authenticated
user id on the server side. The client can never supply a RAG identity.

Embeddings: deterministic feature-hashing vectors (offline, no external
service). If LLM_API_KEY is configured, answers are generated by the LLM
provider; otherwise a grounded extractive composer is used. In both cases
answers are built only from retrieved personal chunks.
"""
from __future__ import annotations

import hashlib
import io
import json
import math
import re
from datetime import datetime, timezone

from boto3.dynamodb.conditions import Key

from . import aws
from .config import settings

EMBED_DIM = 384
CHUNK_SIZE = 700
CHUNK_OVERLAP = 120
MAX_CHUNKS_PER_DOC = 200
MIN_SIMILARITY = 0.10

_STOPWORDS = {
    "the", "a", "an", "and", "or", "of", "to", "in", "is", "are", "was", "were",
    "for", "on", "at", "by", "with", "as", "be", "it", "this", "that", "from",
    "i", "my", "me", "you", "your", "we", "our", "their", "his", "her",
    "what", "which", "who", "whom", "how", "when", "where", "why",
    "do", "does", "did", "have", "has", "had", "can", "could", "will", "would",
    "should", "shall", "may", "might", "not", "no", "if", "then", "than", "so",
    "but", "about", "into", "over", "under", "up", "down", "out", "also",
}


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


# ------------------------------------------------------------------ embeddings

def _tokenize(text: str) -> list[str]:
    tokens = re.findall(r"[a-z0-9]+", text.lower())
    return [t for t in tokens if t not in _STOPWORDS and len(t) > 1]


def embed_text(text: str) -> list[float]:
    """Deterministic feature-hashing embedding (offline, reproducible)."""
    vec = [0.0] * EMBED_DIM
    tokens = _tokenize(text)
    features = list(tokens)
    features += [f"{a}_{b}" for a, b in zip(tokens, tokens[1:])]
    for feat in features:
        digest = hashlib.md5(feat.encode("utf-8")).digest()
        idx = int.from_bytes(digest[:4], "little") % EMBED_DIM
        sign = 1.0 if digest[4] & 1 == 0 else -1.0
        weight = 1.0 if "_" not in feat else 0.5
        vec[idx] += sign * weight
    norm = math.sqrt(sum(v * v for v in vec))
    if norm > 0:
        vec = [v / norm for v in vec]
    return [round(v, 6) for v in vec]


def cosine_similarity(a: list[float], b: list[float]) -> float:
    if not a or not b or len(a) != len(b):
        return 0.0
    return sum(x * y for x, y in zip(a, b))  # vectors are L2-normalized


# ------------------------------------------------------------------ chunking

def chunk_text(text: str) -> list[str]:
    text = re.sub(r"\n{3,}", "\n\n", text.strip())
    if not text:
        return []
    chunks: list[str] = []
    start = 0
    while start < len(text) and len(chunks) < MAX_CHUNKS_PER_DOC:
        end = min(start + CHUNK_SIZE, len(text))
        if end < len(text):
            window = text[start:end]
            # prefer breaking on paragraph, then sentence, then space
            for sep in ("\n\n", ". ", " "):
                cut = window.rfind(sep)
                if cut > CHUNK_SIZE * 0.5:
                    end = start + cut + len(sep)
                    break
        chunk = text[start:end].strip()
        if chunk:
            chunks.append(chunk)
        if end >= len(text):
            break
        start = max(end - CHUNK_OVERLAP, start + 1)
    return chunks


# ------------------------------------------------------------- text extraction

def extract_pages(content: bytes, mime: str, filename: str) -> list[tuple[int, str]]:
    """Extract text per page where the format allows it.

    Returns a list of (page_number, text). ``page_number`` is 1-based for
    paginated formats (PDF) and 0 for flat files. Empty when nothing is
    extractable — callers report that rather than pretending success.
    """
    ext = filename.rsplit(".", 1)[-1].lower() if "." in filename else ""
    try:
        if ext == "pdf" or mime == "application/pdf":
            from pypdf import PdfReader
            reader = PdfReader(io.BytesIO(content))
            pages: list[tuple[int, str]] = []
            for i, page in enumerate(reader.pages[:200], start=1):
                text = (page.extract_text() or "").strip()
                if text:
                    pages.append((i, text))
            return pages
        if ext == "docx":
            import re as _re
            import zipfile
            with zipfile.ZipFile(io.BytesIO(content)) as zf:
                xml = zf.read("word/document.xml").decode("utf-8", "ignore")
            xml = _re.sub(r"</w:p>", "\n", xml)
            text = _re.sub(r"<[^>]+>", "", xml).strip()
            return [(0, text)] if text else []
        if ext in ("txt", "md", "csv", "json", "log", "rtf") or mime.startswith("text/"):
            for enc in ("utf-8", "latin-1"):
                try:
                    text = content.decode(enc).strip()
                    return [(0, text)] if text else []
                except UnicodeDecodeError:
                    continue
    except Exception:
        return []
    return []


def extract_text(content: bytes, mime: str, filename: str) -> str | None:
    """Joined text across all pages (kept for callers that only need text)."""
    pages = extract_pages(content, mime, filename)
    joined = "\n\n".join(t for _, t in pages).strip()
    return joined or None


def profile_summary(profile: dict, role: str = "student") -> str:
    """A plain-text summary of the caller's own profile, shaped for their role."""
    if role == "faculty":
        parts = [
            f"Full name: {profile.get('full_name', '')}",
            "Role: Faculty member",
            f"Institution: {profile.get('institution', '')}",
            f"Faculty ID: {profile.get('faculty_id', '')}",
            f"Department: {profile.get('department', '')}",
            f"Designation: {profile.get('designation', '')}",
            f"Office contact: {profile.get('office_contact', '')}",
            "Areas of expertise: " + ", ".join(profile.get("expertise", []) or []),
            f"Bio: {profile.get('bio', '')}",
        ]
    elif role == "recruiter":
        parts = [
            f"Full name: {profile.get('full_name', '')}",
            "Role: Recruiter",
            f"Company: {profile.get('company', '')}",
            f"Job title: {profile.get('job_title', '')}",
            f"Industry: {profile.get('industry', '')}",
            f"Company website: {profile.get('company_website', '')}",
            "Hiring domains: " + ", ".join(profile.get("hiring_domains", []) or []),
        ]
    elif role == "admin":
        parts = [
            f"Full name: {profile.get('full_name', '')}",
            "Role: Administrator",
            f"Designation: {profile.get('admin_designation', '')}",
            f"Organization: {profile.get('organization', '')}",
        ]
    else:
        parts = [
            f"Full name: {profile.get('full_name', '')}",
            f"Student ID: {profile.get('student_id', '')}",
            f"Institution: {profile.get('institution', '')}",
            f"Course: {profile.get('course', '')}",
            f"Education level: {profile.get('education_level', '')}",
            f"Department: {profile.get('department', '')}",
            f"Year: {profile.get('year', '')}",
            f"Graduation year: {profile.get('graduation_year', '')}",
            f"CGPA: {profile.get('cgpa', '')}",
            f"Bio: {profile.get('bio', '')}",
            "Skills: " + ", ".join(profile.get("skills", []) or []),
            "Achievements: " + ", ".join(profile.get("achievements", []) or []),
        ]
    return "\n".join(p for p in parts if not p.endswith(":"))


# ------------------------------------------------------------- store operations

def instance(user_id: str) -> dict | None:
    resp = aws.table("rag").get_item(Key={"pk": f"RAG#{user_id}", "sk": "INSTANCE"})
    return resp.get("Item")


def create_instance(user_id: str) -> dict:
    item = {
        "pk": f"RAG#{user_id}", "sk": "INSTANCE",
        "user_id": user_id, "enabled": True, "status": "READY",
        "created_at": _now(), "updated_at": _now(), "chunk_count": 0,
    }
    aws.table("rag").put_item(Item=item)
    return item


def set_enabled(user_id: str, enabled: bool, status: str) -> None:
    aws.table("rag").update_item(
        Key={"pk": f"RAG#{user_id}", "sk": "INSTANCE"},
        UpdateExpression="SET enabled = :e, #st = :s, updated_at = :t",
        ExpressionAttributeNames={"#st": "status"},
        ExpressionAttributeValues={":e": enabled, ":s": status, ":t": _now()},
    )


def wipe_user_rag(user_id: str) -> int:
    """Delete every item in the user's personal partition (full opt-out)."""
    tbl = aws.table("rag")
    deleted = 0
    while True:
        resp = tbl.query(KeyConditionExpression=Key("pk").eq(f"RAG#{user_id}"), Limit=100)
        items = resp.get("Items", [])
        if not items:
            break
        with tbl.batch_writer() as batch:
            for it in items:
                batch.delete_item(Key={"pk": it["pk"], "sk": it["sk"]})
                deleted += 1
        if len(items) < 100:
            break
    return deleted


def remove_document_chunks(user_id: str, document_id: str) -> int:
    tbl = aws.table("rag")
    removed = 0
    for prefix in (f"CHUNK#{document_id}#",):
        while True:
            resp = tbl.query(
                KeyConditionExpression=Key("pk").eq(f"RAG#{user_id}") & Key("sk").begins_with(prefix),
                Limit=100,
            )
            items = resp.get("Items", [])
            if not items:
                break
            with tbl.batch_writer() as batch:
                for it in items:
                    batch.delete_item(Key={"pk": it["pk"], "sk": it["sk"]})
                    removed += 1
            if len(items) < 100:
                break
    try:
        tbl.delete_item(Key={"pk": f"RAG#{user_id}", "sk": f"DOC#{document_id}"})
    except Exception:
        pass
    return removed


def upsert_profile_chunk(user_id: str, profile: dict, role: str = "student") -> None:
    text = profile_summary(profile, role)
    if not text.strip():
        return
    vec = embed_text(text)
    aws.table("rag").put_item(Item={
        "pk": f"RAG#{user_id}", "sk": "PROFILE",
        "chunk_id": "profile",
        "text": text,
        "embedding": json.dumps(vec),
        "filename": "Profile information",
        "source": "profile",
        "created_at": _now(),
    })


def ingest_document(user_id: str, document_id: str, filename: str,
                    mime: str, content: bytes) -> str:
    """Extract, chunk, embed into the user's own partition. Idempotent."""
    inst = instance(user_id)
    if not inst or not inst.get("enabled"):
        return "disabled"
    pages = extract_pages(content, mime, filename)
    if not pages:
        return "no_text"

    remove_document_chunks(user_id, document_id)
    tbl = aws.table("rag")
    idx = 0
    for page_no, page_text in pages:
        for chunk in chunk_text(page_text):
            tbl.put_item(Item={
                "pk": f"RAG#{user_id}", "sk": f"CHUNK#{document_id}#{idx:04d}",
                "chunk_id": f"{document_id}#{idx}",
                "document_id": document_id,
                "text": chunk,
                "embedding": json.dumps(embed_text(chunk)),
                "filename": filename,
                "page": page_no,
                "source": "document",
                "created_at": _now(),
            })
            idx += 1
    tbl.put_item(Item={
        "pk": f"RAG#{user_id}", "sk": f"DOC#{document_id}",
        "document_id": document_id, "filename": filename,
        "chunk_count": idx, "status": "indexed" if idx else "no_text",
        "indexed_at": _now(), "created_at": _now(),
    })
    _refresh_count(user_id)
    return "indexed" if idx else "no_text"


def _refresh_count(user_id: str) -> None:
    resp = aws.table("rag").query(
        KeyConditionExpression=Key("pk").eq(f"RAG#{user_id}") & Key("sk").begins_with("CHUNK#"),
        Select="COUNT",
    )
    count = resp.get("Count", 0)
    aws.table("rag").update_item(
        Key={"pk": f"RAG#{user_id}", "sk": "INSTANCE"},
        UpdateExpression="SET chunk_count = :c, updated_at = :t",
        ExpressionAttributeValues={":c": count, ":t": _now()},
    )


# ---------------------------------------------------------------- retrieval

def retrieve(user_id: str, query: str, k: int | None = None) -> list[dict]:
    """Retrieve the most relevant evidence FROM THIS USER'S PARTITION ONLY.

    Hybrid scoring: vector similarity combined with lexical overlap. The
    indexed profile summary is eligible alongside document chunks, and each hit
    carries its page so answers can cite precisely.
    """
    inst = instance(user_id)
    if not inst or not inst.get("enabled"):
        return []
    k = k or settings.retrieval_top_k
    qvec = embed_text(query)
    q_tokens = set(_tokenize(query))
    results: list[dict] = []
    start_key = None
    scanned = 0
    tbl = aws.table("rag")
    while scanned < 5000:
        kwargs = {
            "KeyConditionExpression": Key("pk").eq(f"RAG#{user_id}"),
            "Limit": 500,
        }
        if start_key:
            kwargs["ExclusiveStartKey"] = start_key
        resp = tbl.query(**kwargs)
        for it in resp.get("Items", []):
            sk = it.get("sk", "")
            if sk != "PROFILE" and not sk.startswith("CHUNK#"):
                continue
            try:
                vec = json.loads(it.get("embedding", "[]"))
            except Exception:
                continue
            if not vec:
                continue
            cosine = cosine_similarity(qvec, vec)
            text = it.get("text", "")
            score = 0.7 * cosine + 0.3 * _lexical_overlap(q_tokens, text)
            if score >= MIN_SIMILARITY:
                results.append({
                    "text": text,
                    "filename": it.get("filename", ""),
                    "document_id": it.get("document_id", ""),
                    "page": it.get("page", 0),
                    "source": it.get("source", "document"),
                    "score": round(score, 4),
                })
        scanned += resp.get("Count", 0)
        start_key = resp.get("LastEvaluatedKey")
        if not start_key:
            break
    results.sort(key=lambda r: r["score"], reverse=True)
    return results[:k]


def _lexical_overlap(q_tokens: set[str], text: str) -> float:
    """Fraction of the question's content words that appear in the passage."""
    if not q_tokens:
        return 0.0
    tokens = set(_tokenize(text))
    if not tokens:
        return 0.0
    return len(q_tokens & tokens) / len(q_tokens)


def list_sources(user_id: str) -> dict:
    resp = aws.table("rag").query(
        KeyConditionExpression=Key("pk").eq(f"RAG#{user_id}") & Key("sk").begins_with("DOC#"),
        ScanIndexForward=False,
        Limit=200,
    )
    docs = [{
        "document_id": it.get("document_id", ""),
        "filename": it.get("filename", ""),
        "chunk_count": it.get("chunk_count", 0),
        "indexed_at": it.get("indexed_at", ""),
        "status": it.get("status", ""),
    } for it in resp.get("Items", [])]
    has_profile = aws.table("rag").get_item(
        Key={"pk": f"RAG#{user_id}", "sk": "PROFILE"}
    ).get("Item") is not None
    inst = instance(user_id) or {}
    return {
        "documents": docs,
        "profile_indexed": has_profile,
        "chunk_count": inst.get("chunk_count", 0),
        "status": inst.get("status", "NOT_CREATED"),
        "enabled": bool(inst.get("enabled")),
    }


# ------------------------------------------------------------------ answers

_CROSS_USER_PATTERNS = [
    re.compile(r"\bOBS-[A-Z0-9]{4}-[A-Z0-9]{6}\b"),
    re.compile(r"\b(another|other|someone else'?s|other student'?s|their)\s+student\b", re.I),
    re.compile(r"\bstudent\s*#?\s*0*\d{2,}\b", re.I),
    re.compile(r"\bevery student|\ball students|\bstudents in general\b", re.I),
    re.compile(r"\bother users?|\banother user\b", re.I),
    re.compile(r"\bfaculty members?|\brecruiters?\b.*\b(all|list|every)\b", re.I),
]


def looks_like_cross_user_request(question: str, own_student_id: str = "") -> bool:
    for pattern in _CROSS_USER_PATTERNS:
        for match in pattern.finditer(question):
            if own_student_id and match.group(0).upper() == own_student_id.upper():
                continue
            return True
    return False


